const { app, BrowserWindow, ipcMain } = require('electron');
const path = require('path'); const fs = require('fs'); const http = require('http');
const ROOT = path.join(__dirname, '..', 'src', 'renderer');
let base='';
app.whenReady().then(async () => {
  ipcMain.handle('http:get', async () => ({ ok:true, status:200, text:'{}', finalUrl:'' }));
  ipcMain.handle('net:set-identity', async () => true);
  ipcMain.handle('app:info', async () => ({ version:'t' }));
  ipcMain.handle('app:open-external', async () => true);
  ipcMain.handle('app:fullscreen', async () => true);
  ipcMain.handle('app:win', async () => ({ ok:true }));
  const server = http.createServer((req,res)=>{ let p=decodeURIComponent((req.url||'/').split('?')[0]); if(p==='/')p='/index.html'; const f=path.join(ROOT,p); if(!fs.existsSync(f)){res.writeHead(404).end('no');return;} res.writeHead(200,{'Content-Type': p.endsWith('.css')?'text/css':(p.endsWith('.js')?'text/javascript':'text/html')}); res.end(fs.readFileSync(f)); });
  await new Promise(r=>server.listen(0,'127.0.0.1',r)); base='http://127.0.0.1:'+server.address().port;
  const win = new BrowserWindow({ width:1600, height:900, show:false, paintWhenInitiallyHidden:true, webPreferences:{ preload: path.join(__dirname,'..','src','preload.js'), contextIsolation:true, nodeIntegration:false, webSecurity:false }});
  win.setOpacity(0.01); win.setFocusable(false); win.setSkipTaskbar(true); win.showInactive();
  await win.loadURL(base+'/index.html');
  await new Promise(r=>setTimeout(r,900));
  const info = await win.webContents.executeJavaScript(`(() => {
    const b = document.querySelector('.win-btns');
    const r = b.getBoundingClientRect();
    const cs = getComputedStyle(b);
    const btn = document.querySelector('.win-btn');
    const cs2 = getComputedStyle(btn);
    return { rect:[r.x,r.y,r.width,r.height], display:cs.display, z:cs.zIndex, color:cs2.color, bg:cs2.backgroundColor, count:document.querySelectorAll('.win-btn').length };
  })()`, true);
  console.log('WINBTN ' + JSON.stringify(info));
  const img = await win.webContents.capturePage();
  fs.writeFileSync(path.join(__dirname,'shots','winbtn-test.png'), img.toPNG());
  app.quit();
}).catch(e=>{ console.error('ERR',e); app.exit(1); });
